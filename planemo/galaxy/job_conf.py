"""Utilities for building the job configuration of the Galaxy instances Planemo manages.

Planemo generates a ``job_conf.yml`` for the Galaxy instance it manages (see
:func:`planemo.galaxy.config._handle_job_config_file`). The helpers in this module add
support for ``--tpv_config_file`` - layering user supplied `Total Perspective Vortex
(TPV) <https://github.com/galaxyproject/total-perspective-vortex>`_ configurations on top
of a generated TPV destination.

TPV is what maps tools to job destinations, so it is also the way to give individual
tools their own container settings - for instance a different Docker network mode. A TPV
configuration only changes the tools it mentions, everything else keeps running with the
destination Planemo generates.

``--tpv`` alone is unaffected by this: it uses the configuration galaxy-job-config-init
generates, which references the shared Galaxy TPV database.
"""

import os
from io import StringIO
from typing import (
    Any,
    Dict,
    List,
    Optional,
)

import yaml
from gxjobconfinit import (
    build_job_config,
    ConfigArgs,
)
from gxjobconfinit.generate import DevelopmentContext
from ruamel.yaml import YAML

from planemo.io import write_file

#: Name of the environment generated by ``galaxy-job-config-init --tpv``.
TPV_ENVIRONMENT = "tpv"

#: Base name of the TPV configuration file written next to the generated job config.
TPV_CONFIG_FILE_NAME = "planemo_tpv.yml"

#: Name of the TPV destination generated by Planemo.
TPV_DESTINATION_NAME = "planemo_default"

#: Name of the TPV tool entity all tools inherit from (see ``global.default_inherits``).
TPV_DEFAULT_TOOL = "default"

#: Location TPV is imported from by Galaxy when ``runner: dynamic_tpv`` is used.
TPV_PACKAGE = "total-perspective-vortex"

#: Scheduling tags the generated destination accepts. Galaxy rejects user defined tools
#: unless a destination accepts them explicitly, and container based tools are tagged with
#: the tags of their container system.
TPV_DESTINATION_TAGS = ("docker", "singularity", "tool_type_user_defined")

TPV_CONFIG_HEADER = """\
# TPV (Total Perspective Vortex) configuration generated by Planemo.
#
# Every tool that is not mentioned in another TPV configuration ends up in the
# "planemo_default" destination, which reproduces the job configuration Planemo generates
# for the Galaxy instance. No shared TPV database is referenced, so mapping jobs does not
# depend on network access.
#
# Layer your own configuration on top of this file with ``--tpv_config_file`` to map
# individual tools to other destinations (see the Planemo documentation for an example).
"""

YAML_COMMENT_WIDTH = 1000


def tpv_requested(kwds: Dict[str, Any]) -> bool:
    """Return True if the generated job configuration should use TPV."""
    return bool(kwds.get("tpv") or kwds.get("tpv_config_file"))


def tpv_config_files_requested(kwds: Dict[str, Any]) -> bool:
    """Return True if TPV configurations of the user should be layered on the generated one."""
    return bool(kwds.get("tpv_config_file"))


def tpv_install_command(kwds: Dict[str, Any]) -> Optional[str]:
    """Return a shell command making TPV importable in the Galaxy virtualenv, if needed."""
    if not tpv_requested(kwds):
        return None
    return (
        "if ! python -c 'import tpv' > /dev/null 2>&1; then "
        'echo "Installing Total Perspective Vortex (tpv) into the Galaxy virtualenv."; '
        f"pip install {TPV_PACKAGE}; fi"
    )


def write_job_config(
    job_config_path: str,
    kwds: Dict[str, Any],
    dev_context: Optional[DevelopmentContext] = None,
) -> List[str]:
    """Write a Galaxy job configuration and, if requested, the matching TPV configuration.

    Returns the list of written files, with the job configuration first.
    """
    job_config_path = os.path.abspath(job_config_path)
    init_kwds = _init_kwds(kwds)
    tpv_config_files = _tpv_config_files(kwds)
    contents = build_job_config(ConfigArgs.from_dict(**init_kwds), dev_context)

    written = []
    if tpv_config_files_requested(kwds):
        tpv_config_path = os.path.join(os.path.dirname(job_config_path), TPV_CONFIG_FILE_NAME)
        config = _load_yaml(contents)
        tpv_contents = _apply_tpv(config, tpv_config_path, tpv_config_files, _runner(kwds))
        contents = _dump_yaml(config)
        write_file(tpv_config_path, tpv_contents)
        written.append(tpv_config_path)

    write_file(job_config_path, contents)
    return [job_config_path] + written


def _init_kwds(kwds: Dict[str, Any]) -> Dict[str, Any]:
    """Translate the Planemo options into galaxy-job-config-init arguments."""
    init_kwds = dict(kwds)
    # --tpv_config_file implies TPV
    if init_kwds.get("tpv_config_file"):
        init_kwds["tpv"] = True
    return init_kwds


def _tpv_config_files(kwds: Dict[str, Any]) -> List[str]:
    return [os.path.abspath(path) for path in kwds.get("tpv_config_file") or []]


def _runner(kwds: Dict[str, Any]) -> str:
    """Return the name of the job runner, which is also the name of its environment."""
    return kwds.get("runner") or "local"


def _load_yaml(contents: str):
    """Load generated YAML while preserving its comments."""
    yaml_rt = YAML()
    yaml_rt.width = YAML_COMMENT_WIDTH
    return yaml_rt.load(contents)


def _dump_yaml(config) -> str:
    yaml_rt = YAML()
    yaml_rt.width = YAML_COMMENT_WIDTH
    stream = StringIO()
    yaml_rt.dump(config, stream)
    return stream.getvalue()


def _apply_tpv(config, tpv_config_path: str, tpv_config_files: List[str], runner: str) -> str:
    """Map all tools through TPV and point the job configuration at the generated files.

    Returns the contents of the TPV configuration file that has to be written alongside the
    job configuration.
    """
    execution = config["execution"]
    environments = execution["environments"]
    tpv_environment = environments[TPV_ENVIRONMENT]

    # Tool based environment assignment would bypass TPV, let TPV map every tool.
    config.pop("tools", None)

    tpv_config = {
        "global": {"default_inherits": TPV_DEFAULT_TOOL},
        # Tools that no other configuration mentions are mapped to planemo_default.
        "tools": {TPV_DEFAULT_TOOL: {}},
        "destinations": {TPV_DESTINATION_NAME: _tpv_destination(environments, runner)},
    }

    # Only reference the generated configuration and the files Planemo was asked for: the
    # shared database galaxy-job-config-init points at would assign tools to destinations
    # that are not defined here.
    config_key = _tpv_config_key(tpv_environment)
    tpv_environment[config_key] = [tpv_config_path] + tpv_config_files

    return TPV_CONFIG_HEADER + yaml.safe_dump(tpv_config, sort_keys=False)


def _tpv_config_key(tpv_environment) -> str:
    """Return the name of the environment key referencing TPV configurations."""
    for key in ("tpv_configs", "tpv_config_files"):
        if key in tpv_environment:
            return key
    raise ValueError(f"TPV environment [{TPV_ENVIRONMENT}] references no TPV configuration.")


def _tpv_destination(environments, runner: str) -> Dict[str, Any]:
    """Build a TPV destination from the generated job runner environment."""
    environment = _job_runner_environment(environments, runner)
    # Everything Galaxy accepts in a job destination (i.e. an environment without its runner)
    # has to be nested under params in TPV.
    params = {key: value for key, value in environment.items() if key != "runner"}
    destination: Dict[str, Any] = {
        "runner": environment.get("runner", runner),
        "scheduling": {"accept": list(TPV_DESTINATION_TAGS)},
    }
    if params:
        destination["params"] = params
    return destination


def _job_runner_environment(environments, runner: str) -> Dict[str, Any]:
    """Return the environment describing the job runner (i.e. everything but TPV itself)."""
    if runner in environments and runner != TPV_ENVIRONMENT:
        return environments[runner]
    for name, environment in environments.items():
        if name != TPV_ENVIRONMENT:
            return environment
    return {}
